public class ValoriBooleani {
    public static void main(String[] args) {
        boolean vero = true;
        boolean falso = false;
        System.out.println("L'affermazione è " + vero);
        System.out.println("Il contrario è " + falso);
    }
}
/*
 Il tipo 'boolean' in Java ammette unicamente i valori letterali
 'true' o 'false'. A differenza di linguaggi come C/C++, non è compatibile
 con i numeri (0 o 1) e non permette conversioni numeriche dirette.
*/