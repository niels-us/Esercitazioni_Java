package E1;

public class StampaSequenza {
    public static void main(String[] args) {
        System.out.print("Uno ");
        System.out.print("Due ");
        System.out.print("Tre");
        System.out.println("Uno ");
        System.out.println("Due ");
        System.out.println("Tre");
    }
}

/*
 'print' stampa il testo e mantiene il cursore sulla stessa riga;
 'println' stampa il testo e sposta automaticamente il cursore alla riga successiva.
*/
